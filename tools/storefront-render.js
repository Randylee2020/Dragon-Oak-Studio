const layout = ({ title, description, canonicalPath, ogImage, ogImageAlt, noindex, jsonLd, activeNav, body }) => {
  const fullTitle = `${title} | ${SITE_NAME}`;
  const canonical = absoluteUrl(canonicalPath);
  const image = absoluteUrl(ogImage || DEFAULT_SOCIAL_IMAGE);
  const imageAlt = ogImageAlt || "Dragon Oak Studio - Crafted by Fire. Designed to Last.";
  const jsonLdTags = (jsonLd || [])
    .map((entry) => `  <script type="application/ld+json">${safeJsonLd(entry)}</script>`)
    .join("\n");

  return `<!DOCTYPE html>
<!-- ${GENERATED_NOTE} -->
<html lang="en">
<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1.0" />
  <meta name="description" content="${escapeHtml(description)}" />
  <title>${escapeHtml(fullTitle)}</title>
  <link rel="canonical" href="${escapeHtml(canonical)}" />${noindex ? '\n  <meta name="robots" content="noindex, follow" />' : ""}
  <meta property="og:type" content="website" />
  <meta property="og:url" content="${escapeHtml(canonical)}" />
  <meta property="og:title" content="${escapeHtml(fullTitle)}" />
  <meta property="og:description" content="${escapeHtml(description)}" />
  <meta property="og:image" content="${escapeHtml(image)}" />
  <meta property="og:image:alt" content="${escapeHtml(imageAlt)}" />
  <meta name="twitter:card" content="summary_large_image" />
  <meta name="twitter:title" content="${escapeHtml(fullTitle)}" />
  <meta name="twitter:description" content="${escapeHtml(description)}" />
  <meta name="twitter:image" content="${escapeHtml(image)}" />
  <link rel="icon" href="/assets/dragon-oak-logo.webp" type="image/webp" />
  <link rel="stylesheet" href="/css/styles.css" />
  <link rel="stylesheet" href="/css/storefront.css" />
  <script src="/js/main.js?v=phase-ii-intro" defer></script>
  <script src="/js/shop.js" defer></script>
${jsonLdTags}
</head>

<body>
${headerHtml({ activeNav })}

  <main class="shop-main">
${body}
  </main>

${footerHtml()}
</body>
</html>
`;
};

const breadcrumbJsonLd = (crumbs) => ({
  "@context": "https://schema.org",
  "@type": "BreadcrumbList",
  itemListElement: crumbs.map((crumb, index) => ({
    "@type": "ListItem",
    position: index + 1,
    name: crumb.name,
    item: absoluteUrl(crumb.path),
  })),
});

const breadcrumbHtml = (crumbs) => {
  const items = crumbs
    .map((crumb, index) =>
      index === crumbs.length - 1
        ? `<li aria-current="page">${escapeHtml(crumb.name)}</li>`
        : `<li><a href="${escapeHtml(crumb.path)}">${escapeHtml(crumb.name)}</a></li>`
    )
    .join("");

  return `<nav class="breadcrumb" aria-label="Breadcrumb"><ol>${items}</ol></nav>`;
};

const typeBadge = (productType) =>
  `<span class="type-badge type-${productType === "digital_download" ? "digital" : "physical"}">${escapeHtml(
    PRODUCT_TYPE_LABELS[productType] || productType
  )}</span>`;

const productCard = (product) => {
  const image = product.images[0];

  return `<article class="shop-card" data-product-type="${escapeHtml(product.productType)}" data-subcollection="${escapeHtml(
    product.subcollection || ""
  )}">
            <a class="shop-card-link" href="${escapeHtml(product.url)}">
              <div class="shop-card-art">
                <img src="${escapeHtml(imageUrl(image.path))}" alt="${escapeHtml(image.alt)}" loading="lazy" decoding="async" />
              </div>
              <div class="shop-card-body">
                ${typeBadge(product.productType)}
                <h3>${escapeHtml(product.title)}</h3>
                <p class="shop-card-price">${product.price ? escapeHtml(product.price.display) : "Ask for details"}</p>
              </div>
            </a>
          </article>`;
};

const productGrid = (products) => `<div class="shop-grid" data-shop-grid>
          ${products.map(productCard).join("\n          ")}
        </div>`;

const collectionCard = (collection) => `<a class="collection-card" href="${escapeHtml(collection.url)}">
          <span class="collection-count">${collection.count > 0 ? pluralPieces(collection.count) : "Coming soon"}</span>
          <h3>${escapeHtml(collection.name)}</h3>
          <p>${escapeHtml(collection.tagline)}</p>
          <span class="collection-cta" aria-hidden="true">Browse →</span>
        </a>`;

const collectionGrid = (collections) => `<div class="collection-grid">
        ${collections.map(collectionCard).join("\n        ")}
      </div>`;

