// Static HTML renderers for the Dragon Oak storefront. Pure functions: (public catalog) -> strings.
//
// SECURITY: renderers only ever receive the PUBLIC catalog projection (api/_lib/catalog.js buildPublicCatalog), so
// digital-file references, internal notes and Etsy internals cannot appear in any page. Every dynamic value is HTML-escaped.
const { PRODUCT_TYPE_LABELS } = require("../api/_lib/catalog");

const SITE_ORIGIN = "https://dragonoakstudio.com";
const SITE_NAME = "Dragon Oak Studio";
const DEFAULT_SOCIAL_IMAGE = "/assets/dragon-oak-social-share.jpg";
const GENERATED_NOTE = "Generated by tools/build-storefront.js from catalog/. Do not edit by hand; run npm run catalog:build.";

const HOME_MARKERS = {
  start: "<!-- storefront:collections:start (generated by tools/build-storefront.js; do not edit between the markers) -->",
  end: "<!-- storefront:collections:end -->",
};

const escapeHtml = (value) =>
  String(value === undefined || value === null ? "" : value)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");

// JSON for <script type="application/ld+json">: neutralise anything that could close the script element early.
const safeJsonLd = (value) =>
  JSON.stringify(value)
    .replace(/</g, "\\u003c")
    .replace(/>/g, "\\u003e")
    .replace(/&/g, "\\u0026")
    .split(String.fromCharCode(0x2028))
    .join("\\u2028")
    .split(String.fromCharCode(0x2029))
    .join("\\u2029");

const absoluteUrl = (pathOrUrl) => (/^https?:\/\//i.test(pathOrUrl) ? pathOrUrl : `${SITE_ORIGIN}${pathOrUrl}`);
const assetUrl = (relativePath) => `/${relativePath}`;
const imageUrl = (pathOrUrl) => (/^https?:\/\//i.test(pathOrUrl) ? pathOrUrl : assetUrl(pathOrUrl));
const pluralPieces = (count) => (count === 1 ? "1 piece" : `${count} pieces`);

const paragraphs = (text) =>
  String(text || "")
    .split(/\n{2,}/)
    .map((block) => block.trim())
    .filter(Boolean)
    .map((block) => `<p>${escapeHtml(block).replace(/\n/g, "<br />")}</p>`)
    .join("\n            ");

